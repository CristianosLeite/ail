#!/bin/sh
# Print stage1/tables.ai: the read-only tables of stage1, taken from the bytes
# that stage0/ailc.s assembles to, which makes the assembly their one
# definition. Usage: tools/tables.sh > stage1/tables.ai  (or: make tables)
# Needs as, nm, objcopy, od and awk.
set -eu
cd "$(dirname "$0")/.."
t=$(mktemp -d)
trap 'rm -rf "$t"' EXIT
as -o "$t/a.o" stage0/ailc.s
objcopy -O binary -j .rodata "$t/a.o" "$t/rodata"
# the symbols of .rodata by address, and the sizes that stage0 names with .equ
nm -n "$t/a.o" | awk '$2 == "r" || $2 == "R" || $2 == "a" { print $1, $2, $3 }' > "$t/syms"
od -An -v -tu1 "$t/rodata" | tr -s ' \n' '\n\n' | sed '/^$/d' > "$t/bytes"
awk -v syms="$t/syms" '
function hex(s,   i, n, c) {
    n = 0
    for (i = 1; i <= length(s); i++) {
        c = index("0123456789abcdef", tolower(substr(s, i, 1))) - 1
        n = n * 16 + c
    }
    return n
}
# the bytes of a table that ends where the next symbol starts
function upto(name,   i) {
    for (i = 1; i <= nsym; i++) if (symname[i] == name) return symaddr[i + 1] - symaddr[i]
}
function line(prefix, from, n,   i, s) {
    s = prefix
    for (i = 0; i < n; i++) s = s " " b[from + i]
    print s
}
function plain(name, n, comment) {
    if (comment != "") print comment
    line("data " name, at[name], n)
}
BEGIN {
    while ((getline l < syms) > 0) {
        split(l, f, " ")
        if (f[2] == "a") { size[f[3]] = hex(f[1]); continue }
        nsym++; symname[nsym] = f[3]; symaddr[nsym] = hex(f[1]); at[f[3]] = hex(f[1])
    }
}
{ b[NR - 1] = $1 }
END {
    print "# ailc stage1 -- the read-only tables of stage1/ailc.ai, which compiles this"
    print "# file in place with use. Generated by tools/tables.sh from the bytes that"
    print "# stage0/ailc.s assembles to: change the tables there and run make tables."
    print "# the ELF header (type 3: loaded anywhere) and the two program headers"
    for (i = 0; i < size["HDRSZ"]; i += 16) line(i ? "data" : "data hdr", at["hdr"] + i, 16)
    print "# statements: name length, name, operand count, flags (two bytes), code"
    print "# length, code. Flags 255 mark a statement parsed on its own, numbered by"
    print "# its operand count."
    p = at["optab"]; first = 1
    while (b[p] != 0) {
        n = b[p]; name = ""
        for (i = 1; i <= n; i++) name = name sprintf("%c", b[p + i])
        p += n + 1
        s = (first ? "data optab " : "data ") n " \"" name "\" " b[p] " " b[p + 1] " " b[p + 2] " " b[p + 3]
        c = b[p + 3]; p += 4
        for (i = 0; i < c; i++) s = s " " b[p + i]
        p += c; first = 0
        print s
    }
    print "data 0"
    print "# names that sys accepts for a syscall number, unless the program has a"
    print "# const of that name: name length, name, number as two bytes"
    p = at["sysnames"]; first = 1
    while (b[p] != 0) {
        n = b[p]; name = ""
        for (i = 1; i <= n; i++) name = name sprintf("%c", b[p + i])
        p += n + 1
        print (first ? "data sysnames " : "data ") n " \"" name "\" " b[p] " " b[p + 1]
        p += 2; first = 0
    }
    print "data 0"
    print "# the code of ret: six pops and ret"
    line("data retc", at["retcode"], size["RETSZ"])
    plain("fnpush", size["FNPUSHSZ"], "# function entry: six pushes")
    plain("zeroes", upto("zeroes"), "# xor eax,eax ; xor edi,edi ; xor esi,esi ; xor edx,edx ; xor r10d,r10d ;\n# xor r8d,r8d -- and how many of those bytes clear the first n results")
    plain("zerolen", upto("zerolen"), "")
    plain("pushlen", upto("pushlen"), "# bytes of fnpush that save the first n registers; 10 minus that many bytes\n# of the pops restore all but those")
    plain("probe", size["PROBESZ"], "# sub rsp, <frame> for a frame of a page or more, a page at a time with a\n# touch of each; the frame is the four bytes at offset 2")
    plain("regtab", upto("regtab"), "# per argument: REX prefix or 0, mov opcode")
    plain("argnum", upto("argnum"), "# per argument: x86 register number")
    plain("varnum", upto("varnum"), "# per variable: x86 register number")
    plain("exit0", size["EXIT0SZ"], "# mov eax,60 ; xor edi,edi ; syscall")
}' "$t/bytes"
